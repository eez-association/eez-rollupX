/// Dedicated predeploy, distinct from the EIP-2935 L2 block-hash ring.
pub const HISTORY_ADDRESS: Address = address!("eeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeee0077");
/// Maximum consecutive records in one mandatory scheduled import.
pub const MAX_IMPORT_HEADERS: usize = 64;
/// Separate system-call budget; excluded from transaction gas accounting.
pub const IMPORT_GAS_LIMIT: u64 = 2_000_000;
/// Pre-decode byte ceiling for supported L1 execution headers.
pub const MAX_HEADER_BYTES: usize = 2048;

sol! {
    interface IL1BlockhashContract {
        function importHistory(uint64 cutoff, bytes32[] hashes) external;
        function getL1BlockHash(uint64 number) external view returns (bytes32);
        function current() external view returns (uint64 number, bytes32 hash);
    }
}

/// Scalar slots in L1BlockhashContract. Hashes occupy mapping slot zero.
pub const FIRST_NUMBER_SLOT: u64 = 1;
/// Current selected number, also the last stored history number.
pub const ENDPOINT_SLOT: u64 = 2;
/// Next cutoff to install, including after an empty import.
pub const NEXT_CUTOFF_SLOT: u64 = 3;
/// Committed period in seconds between cutoffs.
pub const INTERVAL_SLOT: u64 = 4;
/// Committed offset in seconds from cutoff to installation.
pub const UPDATE_DELAY_SLOT: u64 = 5;
/// Contract-side bound, required to equal the shared import limit.
pub const MAX_IMPORT_SLOT: u64 = 6;

/// Solidity mapping key for an exact historical number in slot zero.
pub fn hash_storage_key(number: u64) -> U256 {
    U256::from_be_bytes(keccak256((number, U256::ZERO).abi_encode()).0)
}

/// Canonical fresh-genesis storage. History starts at the authenticated selected
/// bootstrap header; earlier numbers are deliberately unavailable.
pub fn bootstrap_storage(
    number: u64,
    hash: B256,
    schedule: HistorySchedule,
) -> Result<BTreeMap<B256, B256>, ProfileError> {
    if hash.is_zero() {
        return Err(ProfileError("zero bootstrap L1 hash"));
    }
    let mut storage = BTreeMap::new();
    for (slot, value) in [
        (FIRST_NUMBER_SLOT, number),
        (ENDPOINT_SLOT, number),
        (NEXT_CUTOFF_SLOT, schedule.first_cutoff()),
        (INTERVAL_SLOT, schedule.interval()),
        (UPDATE_DELAY_SLOT, schedule.delay()),
        (MAX_IMPORT_SLOT, MAX_IMPORT_HEADERS as u64),
    ] {
        storage.insert(U256::from(slot).into(), U256::from(value).into());
    }
    storage.insert(hash_storage_key(number).into(), hash);
    Ok(storage)
}

/// Supported historical execution-header layouts. Activation coordinates come
/// from the fixed L1 profile, never a witness's own claims about its fork.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Deserialize, Serialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct HeaderRules {
    /// First block with a base-fee field; None means absent throughout the profile.
    pub london_block: Option<u64>,
    /// First timestamp requiring a withdrawals root.
    pub shanghai_time: Option<u64>,
    /// First timestamp requiring both blob fields and the parent beacon root.
    pub cancun_time: Option<u64>,
    /// First timestamp requiring the execution requests hash.
    pub prague_time: Option<u64>,
    /// First unsupported header layout, if scheduled (e.g. Amsterdam).
    pub unsupported_time: Option<u64>,
}

impl HeaderRules {
    /// Reject missing, premature and unsupported fields; this does not verify L1 execution.
    pub fn validate(&self, header: &Header) -> Result<(), ProfileError> {
        let active = |at: Option<u64>| at.is_some_and(|at| header.timestamp >= at);
        let london = self.london_block.is_some_and(|at| header.number >= at);
        if active(self.unsupported_time)
            || header.extra_data.len() > 32
            || header.base_fee_per_gas.is_some() != london
            || header.withdrawals_root.is_some() != active(self.shanghai_time)
            || header.blob_gas_used.is_some() != active(self.cancun_time)
            || header.excess_blob_gas.is_some() != active(self.cancun_time)
            || header.parent_beacon_block_root.is_some() != active(self.cancun_time)
            || header.requests_hash.is_some() != active(self.prague_time)
            || header.slot_number.is_some()
            || header.block_access_list_hash.is_some()
        {
            return Err(ProfileError(
                "L1 header does not match configured fork layout",
            ));
        }
        Ok(())
    }
}

/// Canonically decoded, locally hashed header checked against configured fork fields.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CheckedHeader {
    header: Header,
    hash: B256,
}

impl CheckedHeader {
    /// The exact decoded fields; linkage and final anchor authority are separate checks.
    pub const fn header(&self) -> &Header {
        &self.header
    }
    /// Keccak of the exact canonical raw header bytes.
    pub const fn hash(&self) -> B256 {
        self.hash
    }
}

/// A bounded contiguous chain. Its first header's predecessor is deliberately
/// not assumed authentic: matching the L2 endpoint and the final on-chain
/// anchor supplies the two required bindings.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct HeaderChain {
    headers: Vec<CheckedHeader>,
}

impl HeaderChain {
    /// Checked headers in consecutive block-number order.
    pub fn headers(&self) -> &[CheckedHeader] {
        &self.headers
    }

    /// Restore an exact retained streaming checkpoint. A caller may discard a
    /// suffix, never manufacture evidence beyond the validated chain length.
    pub fn prefix(&self, length: usize) -> Result<Self, ProfileError> {
        let headers = self.headers.get(..length).ok_or(ProfileError(
            "L1 evidence checkpoint exceeds retained chain",
        ))?;
        Ok(Self {
            headers: headers.to_vec(),
        })
    }

    /// Retain an inclusive, already checked number range. This cannot invent a
    /// gap or expand evidence beyond the original chain.
    pub fn range(&self, first: u64, last: u64) -> Result<Self, ProfileError> {
        let origin = self
            .headers
            .first()
            .ok_or(ProfileError("missing L1 header evidence"))?
            .header
            .number;
        let start = first
            .checked_sub(origin)
            .and_then(|n| usize::try_from(n).ok())
            .ok_or(ProfileError("L1 range starts before evidence"))?;
        let end = last
            .checked_sub(origin)
            .and_then(|n| usize::try_from(n).ok())
            .ok_or(ProfileError("L1 range ends before evidence"))?;
        let headers = self
            .headers
            .get(start..=end)
            .ok_or(ProfileError("L1 range exceeds evidence"))?;
        if headers.is_empty() {
            return Err(ProfileError("empty L1 evidence range"));
        }
        Ok(Self {
            headers: headers.to_vec(),
        })
    }

    /// Canonical raw bytes for transport/public reconstruction. Decoding already
    /// required byte-for-byte equality with this encoding.
    pub fn raw_headers(&self) -> impl Iterator<Item = Bytes> + '_ {
        self.headers
            .iter()
            .map(|header| alloy_rlp::encode(&header.header).into())
    }
    /// Last supplied header, or an error when no evidence has arrived.
    pub fn endpoint(&self) -> Result<&CheckedHeader, ProfileError> {
        self.headers
            .last()
            .ok_or(ProfileError("missing L1 header evidence"))
    }

    /// Validate a whole segment before publishing any progress. Rejected frames
    /// therefore cannot poison a retained session's prefix or rewind checkpoint.
    pub fn append(
        &mut self,
        segment: &[Bytes],
        rules: &HeaderRules,
        max_headers: usize,
    ) -> Result<(), ProfileError> {
        if self
            .headers
            .len()
            .checked_add(segment.len())
            .is_none_or(|n| n > max_headers)
        {
            return Err(ProfileError("L1 header count limit"));
        }
        let mut checked = Vec::<CheckedHeader>::with_capacity(segment.len());
        for raw in segment {
            if raw.is_empty() || raw.len() > MAX_HEADER_BYTES {
                return Err(ProfileError("L1 header byte limit"));
            }
            let header: Header =
                alloy_rlp::decode_exact(raw).map_err(|_| ProfileError("invalid L1 header RLP"))?;
            if alloy_rlp::encode(&header) != raw.as_ref() {
                return Err(ProfileError("noncanonical L1 header RLP"));
            }
            rules.validate(&header)?;
            let hash = keccak256(raw);
            if let Some(previous) = checked.last().or_else(|| self.headers.last())
                && (previous.header.number.checked_add(1) != Some(header.number)
                    || header.parent_hash != previous.hash
                    || header.timestamp <= previous.header.timestamp)
            {
                return Err(ProfileError("nonconsecutive L1 ancestry"));
            }
            checked.push(CheckedHeader { header, hash });
        }
        self.headers.extend(checked);
        Ok(())
    }

    /// Exact-number lookup; absent evidence is an error, never a zero header.
    pub fn at(&self, number: u64) -> Result<&CheckedHeader, ProfileError> {
        let first = self
            .headers
            .first()
            .ok_or(ProfileError("missing L1 header evidence"))?;
        let index = number
            .checked_sub(first.header.number)
            .and_then(|n| usize::try_from(n).ok())
            .ok_or(ProfileError("L1 header outside supplied evidence"))?;
        self.headers
            .get(index)
            .ok_or(ProfileError("L1 header outside supplied evidence"))
    }

    /// Select the latest eligible header. When there is no successor yet,
    /// execution is provisional: Finalize must call `verify_cutoff` before any
    /// signature. Later contradictory evidence never rewrites executed facts.
    pub fn select(&self, cutoff: u64) -> Result<&CheckedHeader, ProfileError> {
        let count = self
            .headers
            .partition_point(|h| h.header.timestamp <= cutoff);
        count
            .checked_sub(1)
            .and_then(|index| self.headers.get(index))
            .ok_or(ProfileError("missing L1 source at cutoff"))
    }

    /// Complete maximality against the selected mode's exact endpoint. Only
    /// actual-parent mode has the last-produced-block exception.
    pub fn verify_cutoff(
        &self,
        cutoff: u64,
        selected: B256,
        anchor: EvidenceAnchor,
    ) -> Result<(), ProfileError> {
        self.verify_anchor(anchor)?;
        let source = self.select(cutoff)?;
        if source.hash != selected {
            return Err(ProfileError("L1 source is not maximal at cutoff"));
        }
        if source.hash == self.endpoint()?.hash {
            match anchor {
                EvidenceAnchor::ActualParent {
                    target_timestamp, ..
                } if target_timestamp > cutoff => {}
                _ => return Err(ProfileError("missing successor after L1 source cutoff")),
            }
        }
        Ok(())
    }

    /// Reject reserved selectors, impossible timing and any missing or extra chain suffix.
    pub fn verify_anchor(&self, anchor: EvidenceAnchor) -> Result<(), ProfileError> {
        let end = self.endpoint()?;
        let (number, hash) = match anchor {
            EvidenceAnchor::ActualParent {
                number,
                hash,
                target_timestamp,
            } => {
                if number == u64::MAX || target_timestamp <= end.header.timestamp {
                    return Err(ProfileError("invalid actual-parent time or number"));
                }
                (number, hash)
            }
            EvidenceAnchor::Historical { number, hash } => {
                if number == 0 || number == u64::MAX {
                    return Err(ProfileError("reserved historical anchor selector"));
                }
                (number, hash)
            }
        };
        if hash.is_zero() || end.header.number != number || end.hash != hash {
            return Err(ProfileError("L1 evidence does not end at exact anchor"));
        }
        Ok(())
    }
}

/// Ready evidence only. Runtime acquisition must happen before execution;
/// implementations must never perform network or blocking disk I/O here.
/// An offline prover supplies only its request's checked witness snapshot.
pub trait L1HistorySource: Debug + Send + Sync {
    /// Supply a contiguous chain containing the authenticated prior endpoint
    /// and all headers needed to select at `cutoff`. Final anchor/maximality
    /// authorization is a separate caller obligation.
    fn headers(&self, cutoff: u64) -> Result<Arc<HeaderChain>, ProfileError>;
}

/// Immutable evidence owned by one execution request, with no provider/cache fallback.
#[derive(Debug, Clone)]
pub struct WitnessHistory(
    /// Checked request-local chain; its final anchor still requires authorization.
    pub Arc<HeaderChain>,
);

impl L1HistorySource for WitnessHistory {
    fn headers(&self, cutoff: u64) -> Result<Arc<HeaderChain>, ProfileError> {
        self.0.select(cutoff)?;
        Ok(Arc::clone(&self.0))
    }
}

/// Claimed anchor used by offline checks. Only matching on-chain custom data
/// authenticates it; constructing this value never grants signing authority.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum EvidenceAnchor {
    /// Bind the last produced block before an exact proposed inclusion timestamp.
    ActualParent {
        /// Exact execution-block number at the chain endpoint.
        number: u64,
        /// Exact locally computed endpoint hash to bind on-chain.
        hash: B256,
        /// Exact inclusion timestamp, greater than the supplied parent timestamp.
        target_timestamp: u64,
    },
    /// Bind a recent produced block; on-chain inclusion enforces the age window.
    Historical {
        /// Exact execution-block number at the chain endpoint.
        number: u64,
        /// Exact locally computed endpoint hash to bind on-chain.
        hash: B256,
    },
}

/// Checked fixed timing parameters, shared by production, replay and reconstruction.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct HistorySchedule {
    first_cutoff: u64,
    block_interval: u64,
    interval: u64,
    delay: u64,
}

impl HistorySchedule {
    /// Check offset, nonzero cadence, bootstrap underflow and initial-update overflow.
    pub fn new(
        first_cutoff: u64,
        block_interval: u64,
        positions: u32,
        offset: u32,
    ) -> Result<Self, ProfileError> {
        if block_interval == 0 || positions < 2 || offset >= positions {
            return Err(ProfileError("invalid history update schedule"));
        }
        let interval = block_interval
            .checked_mul(u64::from(positions))
            .ok_or(ProfileError("history interval overflow"))?;
        let delay = block_interval
            .checked_mul(u64::from(offset) + 1)
            .ok_or(ProfileError("history delay overflow"))?;
        first_cutoff
            .checked_sub(interval)
            .ok_or(ProfileError("bootstrap cutoff underflow"))?;
        first_cutoff
            .checked_add(delay)
            .ok_or(ProfileError("first history update overflow"))?;
        Ok(Self {
            first_cutoff,
            block_interval,
            interval,
            delay,
        })
    }

    /// Seconds between successive source cutoffs.
    pub const fn interval(&self) -> u64 {
        self.interval
    }
    /// Seconds from a source cutoff to its pre-execution installation.
    pub const fn delay(&self) -> u64 {
        self.delay
    }
    /// First post-genesis source cutoff, equal to genesis timestamp.
    pub const fn first_cutoff(&self) -> u64 {
        self.first_cutoff
    }
    /// Cutoff selecting the genesis origin before the first delayed update.
    pub const fn bootstrap_cutoff(&self) -> u64 {
        self.first_cutoff - self.interval
    }

    /// Derive the active cutoff at an aligned L2 timestamp, retaining it across Sync.
    pub fn source_cutoff(&self, timestamp: u64) -> Result<u64, ProfileError> {
        let elapsed = timestamp
            .checked_sub(self.first_cutoff)
            .ok_or(ProfileError("L2 timestamp precedes history schedule"))?;
        if !elapsed.is_multiple_of(self.block_interval) {
            return Err(ProfileError("L2 timestamp is outside history schedule"));
        }
        Ok(if elapsed < self.delay {
            self.bootstrap_cutoff()
        } else {
            // Both addends are bounded above by timestamp.
            self.first_cutoff + ((elapsed - self.delay) / self.interval) * self.interval
        })
    }

    /// Derive all inputs from authenticated parent storage and checked headers.
    /// The caller must authenticate the parent, execute this exact call and
    /// resolve source maximality at Finalize. No stored hash is overwritten.
    pub fn execution(
        &self,
        timestamp: u64,
        state: HistoryState,
        chain: &HeaderChain,
    ) -> Result<HistoryExecution, ProfileError> {
        if timestamp <= self.first_cutoff {
            return Err(ProfileError(
                "history execution requires a post-genesis block",
            ));
        }
        let cutoff = self.source_cutoff(timestamp)?;
        let updating = cutoff.checked_add(self.delay) == Some(timestamp);
        let expected_next = if updating {
            cutoff
        } else {
            cutoff
                .checked_add(self.interval)
                .ok_or(ProfileError("next cutoff overflow"))?
        };
        if state.first_number > state.endpoint
            || state.next_cutoff != expected_next
            || chain.at(state.endpoint)?.hash != state.endpoint_hash
        {
            return Err(ProfileError("parent L1 history state mismatch"));
        }
        let prior_cutoff = state
            .next_cutoff
            .checked_sub(self.interval)
            .ok_or(ProfileError("parent history cutoff underflow"))?;
        if chain.select(prior_cutoff)?.hash != state.endpoint_hash {
            return Err(ProfileError("inherited L1 source is not maximal"));
        }
        let source = chain.select(cutoff)?;
        let import = if updating {
            let count = source
                .header
                .number
                .checked_sub(state.endpoint)
                .and_then(|n| usize::try_from(n).ok())
                .filter(|&n| n <= MAX_IMPORT_HEADERS)
                .ok_or(ProfileError(
                    "scheduled history import exceeds bound or regresses",
                ))?;
            cutoff
                .checked_add(self.interval)
                .ok_or(ProfileError("next cutoff overflow"))?;
            let mut hashes = Vec::with_capacity(count);
            for offset in 1..=count {
                let number = state
                    .endpoint
                    .checked_add(offset as u64)
                    .ok_or(ProfileError("history endpoint overflow"))?;
                hashes.push(chain.at(number)?.hash);
            }
            Some(
                IL1BlockhashContract::importHistoryCall { cutoff, hashes }
                    .abi_encode()
                    .into(),
            )
        } else {
            if source.hash != state.endpoint_hash {
                return Err(ProfileError("history changed outside scheduled update"));
            }
            None
        };
        Ok(HistoryExecution {
            cutoff,
            origin_number: source.header.number,
            origin_hash: source.hash,
            prev_randao: source.header.mix_hash,
            import,
        })
    }
}

/// Values read from the parent state trie, not from an RPC assertion or caller.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct HistoryState {
    /// Earliest imported number, fixed by genesis.
    pub first_number: u64,
    /// Last imported number in the authenticated parent.
    pub endpoint: u64,
    /// Hash read from the parent mapping at `endpoint`.
    pub endpoint_hash: B256,
    /// Cutoff scheduled after the parent state.
    pub next_cutoff: u64,
}

/// Derived pre-execution input; source maximality still needs final anchor authorization.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HistoryExecution {
    /// Cutoff selecting the source used by this block.
    pub cutoff: u64,
    /// Selected L1 execution block, also the endpoint after a scheduled import.
    pub origin_number: u64,
    /// Exact selected L1 hash.
    pub origin_hash: B256,
    /// Selected header mixHash; must match both the L2 header and EVM environment.
    pub prev_randao: B256,
    /// Canonical system calldata exactly at an update; absent at every other position.
    pub import: Option<Bytes>,
}

