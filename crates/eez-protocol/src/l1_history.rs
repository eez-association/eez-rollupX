/// Highest imported L1 number (uint64 in slot one); zero means empty history.
pub const ENDPOINT_SLOT: u64 = 1;

/// Solidity mapping key for an exact historical number in slot zero.
pub fn hash_storage_key(number: u64) -> U256 {
    U256::from_be_bytes(keccak256((number, U256::ZERO).abi_encode()).0)
}

/// Fresh history is empty. Only the proxy's ERC-1967 pointers have storage;
/// the initial execution origin is authenticated by the genesis configuration.
